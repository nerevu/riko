"""
Checks that the test suite follows its tier layout.

Each test tier folder (``public``, ``internal``, ``functional``) ends its
``__init__.py`` docstring with an index generated by ``manage codegen --tests``. The
check fails when an index is stale, a test sits outside a ``Test<Subject>`` class, a
subject is owned by two files in one tier, a file or folder is misplaced, or a
public test imports a private name. File sizes outside the split/merge bounds are
reported as advice rather than failures.
"""

from __future__ import annotations

import ast
import re
from typing import TYPE_CHECKING, NamedTuple

from ._gen_tier_index import TIERS, gen_subjects, generate_tier_index

if TYPE_CHECKING:
    from collections.abc import Iterator
    from pathlib import Path

FIXTURE_DIRS = frozenset({"workflows", "pyworkflows", "dags", "typing"})
SPLIT_LINES = 2000
MERGE_LINES = 300
HISTORY_NAMES = re.compile(r"^test_(regressions?|fixes|bugs?|misc)\b")


class LayoutIssue(NamedTuple):
    """A test-layout finding; ``fatal`` findings fail the check."""

    path: Path
    lineno: int
    message: str
    fatal: bool = True

    def __str__(self) -> str:
        """Renders the issue as a ``path:line: kind: message`` line."""
        kind = "error" if self.fatal else "advice"
        return f"{self.path}:{self.lineno}: {kind}: {self.message}"


def _gen_file_issues(
    path: Path, tree: ast.Module, lines: int, public: bool
) -> Iterator[LayoutIssue]:
    for node in tree.body:
        if isinstance(
            node, (ast.FunctionDef, ast.AsyncFunctionDef)
        ) and node.name.startswith("test_"):
            message = f"{node.name} must live in a Test<Subject> class"
            yield LayoutIssue(path, node.lineno, message)

    if public:
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom):
                for alias in node.names:
                    if alias.name.startswith("_"):
                        message = f"public tests import supported names: {alias.name}"
                        yield LayoutIssue(path, node.lineno, message)

    if lines > SPLIT_LINES:
        message = (
            f"{lines} lines; move its largest Test<Subject> class into its own file, "
            "then check both files for overlaps, misfits, and move candidates"
        )
        yield LayoutIssue(path, 1, message, fatal=False)
    elif lines < MERGE_LINES:
        message = f"{lines} lines; consider merging it into a neighboring file"
        yield LayoutIssue(path, 1, message, fatal=False)


def _gen_index_issues(tier: Path) -> Iterator[LayoutIssue]:
    init = tier / "__init__.py"

    if generate_tier_index(tier) != init.read_text(encoding="utf-8"):
        message = "the index is stale; run `manage codegen --tests`"
        yield LayoutIssue(init, 1, message)


def _gen_tier_issues(tier: Path) -> Iterator[LayoutIssue]:
    yield from _gen_index_issues(tier)
    owners: dict[str, str] = {}
    modules = (path for path in sorted(tier.glob("*.py")) if path.name != "__init__.py")

    for path in modules:
        if not path.name.startswith("test_"):
            message = "shared helpers belong in a tests/_*.py module"
            yield LayoutIssue(path, 1, message)
        elif HISTORY_NAMES.match(path.name):
            message = "name the file for its subject, not its history"
            yield LayoutIssue(path, 1, message)
        else:
            text = path.read_text(encoding="utf-8")
            tree = ast.parse(text)

            for subject, node in gen_subjects(tree):
                owner = owners.setdefault(subject, path.name)

                if owner != path.name:
                    message = f"{subject} is owned by both {owner} and {path.name}"
                    yield LayoutIssue(path, node.lineno, message)

            lines = len(text.splitlines())
            yield from _gen_file_issues(path, tree, lines, tier.name == "public")


def gen_layout_issues(tests_dir: Path) -> Iterator[LayoutIssue]:
    """
    Finds every way ``tests_dir`` departs from the tier test layout.

    Args:

        tests_dir: The suite's root folder (``tests``).

    Yields:

        One finding per layout departure, failing or advisory.

    """
    allowed = {*TIERS, *FIXTURE_DIRS, "__pycache__"}

    for path in sorted(tests_dir.iterdir()):
        if path.is_dir() and path.name not in allowed:
            message = f"unexpected folder; tests live in {', '.join(TIERS)}"
            yield LayoutIssue(path, 1, message)
        elif path.is_file() and path.name.startswith("test_"):
            yield LayoutIssue(path, 1, f"test files live in {', '.join(TIERS)}")

    for tier in TIERS:
        if (tests_dir / tier).is_dir():
            yield from _gen_tier_issues(tests_dir / tier)
