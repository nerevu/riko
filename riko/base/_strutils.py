"""Provides string, docstring-summary, codegen-note, and source-formatting helpers."""

from __future__ import annotations

from functools import reduce
from subprocess import CalledProcessError, run
from textwrap import wrap
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Sequence

_CODEGEN_CLI = "manage codegen"


def replacer(content: str, old: str, new: str = "_") -> str:
    """
    Replaces ``old`` with ``new`` in ``content``.

    Additionally prepends ``content`` with ``new`` if ``content`` starts with a number
    or non-ASCII character.

    Examples:

        >>> replacer('', '')
        ''
        >>> replacer('1abc', '')
        '_1abc'
        >>> replacer('a.b', '.')
        'a_b'

    """
    if old:
        replaced = content.replace(old, new)
    elif content and (content[0].isdecimal() or not content[0].isascii()):
        replaced = f"{new}{content}"
    else:
        replaced = content

    return replaced


def pythonise(
    content: str, encoding: str = "ascii", replace: Sequence[str] = ("-", ":", "/", "")
) -> str:
    """
    Builds a Python-friendly id from ``content``.

    Args:

        content: The raw id to sanitize.

    Kwargs:

        encoding: The encoding used to drop non-representable characters.
        replace: The substrings replaced with ``_``.

    Returns:

        The sanitized id.

    """
    reduced = reduce(replacer, replace, content)
    return reduced.encode(encoding, "replace").decode(encoding)


def get_doc_summary(obj: object) -> str | None:
    """
    Gets the first non-blank line of an object's docstring.

    Args:

        obj: Any object; one without a docstring has no summary.

    Returns:

        The stripped summary line, or ``None`` when the docstring is missing or blank.

    Examples:

        >>> def shout():
        ...     '''
        ...     Shouts each item.
        ...
        ...     More detail.
        ...     '''
        >>> get_doc_summary(shout)
        'Shouts each item.'
        >>> get_doc_summary(lambda: None)

    """
    lines = (getattr(obj, "__doc__", None) or "").strip().splitlines()
    return lines[0].strip() if lines else None


def get_codegen_note(selector: str) -> str:
    """
    Gets the do-not-edit note naming the command that regenerates a file or block.

    Args:

        selector: The ``manage codegen`` selector that owns the output, such as
            ``"--names"``.

    Returns:

        One line naming the command and forbidding hand edits.

    Examples:

        >>> get_codegen_note("--names")
        'Generated by `manage codegen --names`. Do not edit manually.'

    """
    return f"Generated by `{_CODEGEN_CLI} {selector}`. Do not edit manually."


def wrap_words(
    text: str,
    width: int,
    *,
    lossless: bool = False,
    initial_indent: str = "",
    subsequent_indent: str = "",
) -> list[str]:
    """
    Wraps ``text`` into lines of at most ``width`` columns at the spaces between words.

    Hyphens never break a line. By default a word longer than ``width`` keeps a line
    of its own and drops surrounding whitespace, as prose wraps. A lossless wrap keeps
    every character instead by breaking an overlong word. In that case, the joined lines
    rebuild ``text`` exactly (a string literal split across lines needs).

    Args:

        text: The text to wrap.
        width: The widest line, indent included.

    Kwargs:

        lossless: Whether the joined lines must equal ``text``.
        initial_indent: The prefix of the first line.
        subsequent_indent: The prefix of each later line.

    Returns:

        The wrapped lines; none for empty text.

    Examples:

        >>> wrap_words("a-b cc  ddd", 6)
        ['a-b cc', 'ddd']
        >>> wrap_words("a-b cc  ddd", 6, lossless=True)
        ['a-b cc', '  ddd']
        >>> wrap_words("abcdefgh", 4, lossless=True)
        ['abcd', 'efgh']
        >>> wrap_words("one two", 7, initial_indent="- ", subsequent_indent="  ")
        ['- one', '  two']

    """
    return wrap(
        text,
        width,
        initial_indent=initial_indent,
        subsequent_indent=subsequent_indent,
        expand_tabs=not lossless,
        replace_whitespace=not lossless,
        drop_whitespace=not lossless,
        break_long_words=lossless,
        break_on_hyphens=False,
    )


def ruff_format(code: str) -> str:
    """
    Formats generated Python source with Ruff when available.

    Args:

        code: Python source to format.

    Returns:

        Ruff's formatted source, or the original source when Ruff is unavailable
        or formatting fails.

    Examples:

        >>> ruff_format("x = 1\\n")
        'x = 1\\n'

    """
    try:
        result = run(
            ["ruff", "format", "-"],  # noqa: S607
            input=code,
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, CalledProcessError):
        formatted = code
    else:
        formatted = result.stdout or code

    return formatted
